// Live checks consume Cursor quota. An isolated Mirasim host never changes
// the desktop's agent defaults, accounts, profiles, or running sessions.
import assert from "node:assert/strict"
import { execFile, spawn } from "node:child_process"
import fs from "node:fs/promises"
import net from "node:net"
import os from "node:os"
import path from "node:path"
import { parseArgs, promisify } from "node:util"

const run = promisify(execFile)
const { values } = parseArgs({ options: { model: { type: "string", multiple: true } } })
const selected = values.model || ["4.6", "4.7"]
assert(selected.every((m) => ["4.6", "4.7"].includes(m)), "--model must be 4.6 or 4.7")
const electron = process.env.MIRASIM_VERIFY_BIN || "/Applications/Mirasim.app/Contents/MacOS/Mirasim"
const entry = process.env.MIRASIM_VERIFY_ENTRY || "/Applications/Mirasim.app/Contents/Resources/server.cjs"
const gateway = process.env.MAGPIE_VERIFY_URL || "http://127.0.0.1:3425"
const routing = process.env.MAGPIE_VERIFY_ROUTING_DIR || path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config"), "magpie/routing")
const root = await fs.mkdtemp(path.join(os.tmpdir(), "magpie-context-fast-"))
await fs.chmod(root, 0o700)
await fs.mkdir(path.join(root, "codex-home"))
const env = { ...process.env, ELECTRON_RUN_AS_NODE: "1", MIRASIM_HOME: root, CODEX_HOME: path.join(root, "codex-home") }
delete env.MIRASIM_SESSION_KEY
delete env.MIRASIM_HOST_PORT
// Public model metadata, not an account or a copied sign-in. Mirasim reads
// its speed-tier menu from Codex's cache; an empty isolated home has none.
const bundled = await run("codex", ["debug", "models", "--bundled"], { maxBuffer: 4 << 20 })
const metadata = JSON.parse(bundled.stdout)
// Reuse only public model fields from catalogs already generated by the
// real desktop. Its catalog-generation path is tested separately there;
// this isolated host tests speed selection without that account's roster.
const source = process.env.MIRASIM_VERIFY_CATALOG_DIR || path.join(process.env.MIRASIM_HOME || path.join(os.homedir(), ".mirasim"), "codex/model-catalog")
const catalogs = await fs.readdir(source)
const fields = ["slug", "display_name", "context_window", "max_context_window", "service_tiers", "supported_reasoning_levels"]
for (const alias of ["grok-4.6", "Grok 4.7"]) {
  let found
  for (const file of catalogs.filter((f) => f.endsWith(".json"))) {
    const data = JSON.parse(await fs.readFile(path.join(source, file), "utf8"))
    found = data.models?.find((m) => m.slug === alias) || found
  }
  assert(found, `create a desktop test session on ${alias} before running this verification`)
  metadata.models.push({ ...metadata.models[0], ...Object.fromEntries(fields.filter((k) => found[k] !== undefined).map((k) => [k, found[k]])) })
}
const modelFile = path.join(env.CODEX_HOME, "models_cache.json")
await fs.writeFile(modelFile, JSON.stringify(metadata), { mode: 0o600 })
await fs.writeFile(path.join(env.CODEX_HOME, "config.toml"), `model_catalog_json = ${JSON.stringify(modelFile)}\n`, { mode: 0o600 })
const socket = net.createServer()
await new Promise((resolve, reject) => { socket.once("error", reject); socket.listen(0, "127.0.0.1", resolve) })
const port = String(socket.address().port)
await new Promise((resolve, reject) => socket.close((error) => error ? reject(error) : resolve()))
const host = spawn(electron, [entry, "serve", "--port", port, "--host", "127.0.0.1", "--workdir", root, "--no-open", "--no-im"], {
  env, detached: true, stdio: "ignore",
})
const cli = async (...args) => {
  const { stdout } = await run(electron, [entry, "ui-cli", "--port", port, "--timeout", "90000", ...args], {
    env, timeout: 100000, maxBuffer: 4 << 20,
  })
  return JSON.parse(stdout)
}
async function rollouts(dir) {
  let entries
  try { entries = await fs.readdir(dir, { withFileTypes: true }) } catch (error) {
    if (error.code === "ENOENT") return []
    throw error
  }
  return (await Promise.all(entries.map((e) => e.isDirectory() ? rollouts(path.join(dir, e.name)) :
    e.name.endsWith(".jsonl") ? [path.join(dir, e.name)] : []))).flat()
}
async function routeFor(session) {
  const files = (await fs.readdir(routing)).filter((f) => f.endsWith(".jsonl")).sort().slice(-2)
  const rows = (await Promise.all(files.map(async (f) => (await fs.readFile(path.join(routing, f), "utf8"))
    .trim().split("\n").filter(Boolean).map((line) => JSON.parse(line))))).flat()
  return rows.filter((r) => r.session === session)
}
try {
  let ready = false
  for (let i = 0; i < 30; i++) {
    try { await cli("catalog", "--agent", "codex"); ready = true; break } catch {
      if (host.exitCode !== null) break
      await new Promise((resolve) => setTimeout(resolve, 500))
    }
  }
  assert(ready, "isolated Mirasim host did not start")
  console.log(JSON.stringify({ check: "isolated host", root, port }))
  await cli("config", "set", "relay.mode=local")
  await cli("provider", "save", "--kind", "openai-compatible", "--name", "Magpie verification",
    "--base-url", gateway + "/v1", "--api-key", "magpie", "--wire-api", "responses")
  const exported = await cli("model", "export")
  const provider = exported.providers.find((p) => p.name === "Magpie verification")?.ref
  assert(provider, "isolated provider was not saved")
  for (const [model, window, group, served] of [
    ["grok-4.6", 256000, "group/grok-4-6", "grok-4.6"],
    ["Grok 4.7", 500000, "group/grok-4-7", "grok-4.7@500k"],
  ].filter(([model]) => selected.some((version) => model.includes(version)))) {
    const saved = await cli("profile", "save", "--provider", provider, "--model", model, "--name", model + " verification",
      "--context-window", String(window), "--effort", "high", "--efforts", "low,medium,high,xhigh")
    const profile = saved.profiles.find((p) => p.modelId === model)
    assert(profile?.id)
    for (const tier of ["priority", "default"]) {
      // Use the same supported atom as Settings > Codex > Speed tier.
      // The generic config tree does not persist this field in this build.
      await cli("call", "setAgentDefaults", "--args", JSON.stringify({ agent: "codex", serviceTier: tier }))
      const catalog = await cli("catalog", "--agent", "codex")
      assert(catalog.serviceTiers.some((t) => t.id === "priority"))
      assert.equal(catalog.serviceTier || "default", tier)
      const before = new Set(await rollouts(path.join(env.CODEX_HOME, "sessions")))
      const answer = await cli("prompt", "--agent", "codex", "--cwd", root, "--model", `profile:${profile.id}`,
        "--route", "own", "--effort", "high", "--quiet", "--text", "Do not read files or call tools. What is 2+2? Reply only the number.")
      assert.equal(answer.phase, "done")
      assert.equal(answer.error, null)
      assert.match(answer.text, /\b4\b/)
      const context = await cli("session", "context", "--session", answer.sessionKey)
      assert.equal(context.windowTokens, window * 0.95, "native Codex must use the actual model window, not its generic fallback")
      const fresh = (await rollouts(path.join(env.CODEX_HOME, "sessions"))).filter((p) => !before.has(p))
      assert.equal(fresh.length, 1)
      const id = path.basename(fresh[0]).match(/([a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12})\.jsonl$/i)?.[1]
      assert(id, "native Codex rollout must identify the route session")
      let records = []
      for (let i = 0; i < 10; i++) {
        records = await routeFor(id)
        if (records.length) break
        await new Promise((resolve) => setTimeout(resolve, 100))
      }
      assert.equal(records.length, 1)
      const record = records[0]
      assert.equal(record.group?.ref, group)
      assert.equal(record.status, 200)
      assert.equal(record.tries.length, 1, "a successful fallback does not prove Cursor works")
      assert.equal(record.tries[0].id, "cursor")
      assert.equal(record.tries[0].served, served)
      assert.equal(record.tries[0].effort, "high")
      assert.equal(record.tries[0].tier || "default", tier)
      console.log(JSON.stringify({ check: "native Mirasim to Cursor", model, tier, actualTier: record.tries[0].tier || "default",
        session: id, contextWindow: context.windowTokens, status: record.status, result: "PASS" }))
    }
  }
} finally {
  try { process.kill(-host.pid, "SIGTERM") } catch {}
  await new Promise((resolve) => {
    if (host.exitCode !== null || host.signalCode !== null) return resolve()
    host.once("exit", resolve)
    setTimeout(() => { try { process.kill(-host.pid, "SIGKILL") } catch {} resolve() }, 5000).unref()
  })
  console.log(JSON.stringify({ check: "isolated host stopped", root }))
}
